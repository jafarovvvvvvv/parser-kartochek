"""Регрессия DNS-адаптера: цена в карточке идёт отдельной строкой после
последней характеристики ("...IP54\\n66 490\\xa0₸"), и если в число попадает
перевод строки, характеристика склеивается с ценой ("IP54\\n66 490" превращалось
в 5 466 490). Тест — без сети и без Playwright, только на _parse_price."""
from adapters.dns import _parse_price


def test_цена_после_характеристики_с_переводом_строки_не_склеивается():
    # Воспроизводит реальный текст карточки: характеристика "IP54" на одной
    # строке, цена — на следующей (обычная цена, зачёркнутая старая цена без
    # значка ₸ и цена "в рассрочку" с ₸ — таких совпадений в тексте несколько).
    text = (
        "Защита от пыли и воды IP54\n"
        "66 490 ₸\n"
        "72 190\n"
        "69 990 ₸ в рассрочку"
    )
    assert _parse_price(text) == 66490


def test_цена_с_обычным_пробелом_в_разряде_тоже_читается():
    text = "Экран 6.1\"\n99 990 ₸"
    assert _parse_price(text) == 99990


def test_без_цены_в_тексте_возвращает_none():
    text = "Защита от пыли и воды IP54\nЦвет: чёрный"
    assert _parse_price(text) is None


def test_пустой_текст_возвращает_none():
    assert _parse_price("") is None
